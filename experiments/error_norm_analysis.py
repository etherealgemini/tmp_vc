def parse_args(argv=None):
    p = argparse.ArgumentParser(
        description="Error-norm vs token-index experiment for Qwen2.5-VL-3B-Instruct"
    )
    p.add_argument(
        "--model_path",
        default=os.path.expanduser("~/huggingface/Qwen2.5-VL-3B-Instruct"),
        help="Path to the Qwen2.5-VL-3B-Instruct model directory.",
    )
    p.add_argument(
        "--dataset_path",
        default=None,
        help=(
            "Local path to the MMMU-Pro dataset directory, or omit to stream "
            "from HuggingFace Hub (MMMU/MMMU_Pro, vision subset)."
        ),
    )
    p.add_argument(
        "--dataset_split",
        default="test",
        help="Dataset split to use (default: test).",
    )
    p.add_argument(
        "--sample_index",
        type=int,
        default=0,
        help="Zero-based index of the MMMU-Pro sample to use (default: 0).",
    )
    p.add_argument(
        "--output_dir",
        default="outputs/error_norm",
        help="Directory where plots and raw data are saved (default: outputs/error_norm).",
    )
    p.add_argument(
        "--metric",
        choices=list(METRICS.keys()),
        default="l2",
        help=(
            "Error metric to use.  "
            "'l2'  = per-token L2 norm (default).  "
            "'mse' = per-token mean-squared error."
        ),
    )
    p.add_argument(
        "--decode_steps",
        type=int,
        default=20,
        help="Number of greedy autoregressive decode steps (default: 20).",
    )
    p.add_argument(
        "--device",
        default="cuda" if torch.cuda.is_available() else "cpu",
        help="PyTorch device string (default: cuda if available, else cpu).",
    )
    return p.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)

    if not _HAS_TRANSFORMERS:
        raise RuntimeError(
            "transformers >= 4.51.0 is required.  Install with: "
            "pip install 'transformers>=4.51.0'"
        )

    device = torch.device(args.device)
    dtype  = torch.bfloat16 if device.type == "cuda" else torch.float32
    output_dir = Path(args.output_dir)
    metric_fn  = METRICS[args.metric]
    metric_label = args.metric.upper()

    # 1 – Load dataset sample
    print(f"[1/5] Loading MMMU-Pro Vision sample (index={args.sample_index}) …")
    image, question, _ = load_mmmu_pro_sample(
        dataset_path=args.dataset_path,
        split=args.dataset_split,
        index=args.sample_index,
    )

    # 2 – Load model
    print(f"[2/5] Loading model from {args.model_path} …")
    processor = AutoProcessor.from_pretrained(args.model_path)
    model = Qwen2_5_VLForConditionalGeneration.from_pretrained(
        args.model_path,
        torch_dtype=dtype,
        device_map=str(device),
    )
    model.eval()

    # 3 – Prepare inputs
    print("[3/5] Preparing multimodal inputs …")
    inputs, image_mask = prepare_multimodal_input(
        processor, image, question, device, dtype
    )
    n_img = int(image_mask.sum())
    print(
        f"      Sequence length: {inputs['input_ids'].shape[1]} tokens  "
        f"({n_img} image tokens)"
    )

    # 4 – Collect error norms
    print(
        f"[4/5] Running recompute + reuse passes "
        f"({args.decode_steps} decode steps, metric={args.metric}) …"
    )
    result = collect_error_norms(
        model=model,
        inputs=inputs,
        image_mask=image_mask,
        metric_fn=metric_fn,
        decode_steps=args.decode_steps,
        device=device,
    )

    # 5 – Save outputs
    print(f"[5/5] Saving plots to {output_dir} …")
    output_dir.mkdir(parents=True, exist_ok=True)

    # Raw data
    np.save(output_dir / "error_norms.npy", result["error_norms"])
    meta_to_save = {
        k: int(v) if isinstance(v, (int, np.integer)) else v
        for k, v in result.items()
        if k != "error_norms"
    }
    meta_to_save["metric"] = args.metric
    with open(output_dir / "metadata.json", "w") as fh:
        json.dump(meta_to_save, fh, indent=2)

    # Per-layer plots
    plot_per_layer(
        result["error_norms"],
        output_dir / "per_layer",
        result,
        metric_label,
    )

    # All-layer matrix
    plot_matrix(result["error_norms"], output_dir, result, metric_label)

    print()
    print("Done!")
    print(f"  Output directory : {output_dir}")
    print(f"  Layers           : {result['num_layers']}")
    print(f"  Prefill length   : {result['prefill_len']} tokens")
    print(f"  Decode steps     : {result['decode_len']}")
    print(f"  Image span       : [{result['image_start']}, {result['image_end']})")
    print(f"  Matrix plot      : {output_dir / 'error_matrix.png'}")
    print(f"  Per-layer plots  : {output_dir / 'per_layer'}/ (layer_00.png … )")
    print(f"  Raw data (.npy)  : {output_dir / 'error_norms.npy'}")


if __name__ == "__main__":
    main()

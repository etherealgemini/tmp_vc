@torch.no_grad()
def collect_error_norms(
    model,
    inputs: dict,
    image_mask: torch.BoolTensor,
    metric_fn,
    decode_steps: int = 20,
    device: torch.device = torch.device("cpu"),
) -> dict:
    """
    Run recompute and reuse forward passes and collect per-layer, per-token
    error norms for the full sequence (prefill + autoregressive decoding).

    The two passes differ only in the position IDs assigned to image tokens:

    * **recompute** – natural position IDs (image at its true position P).
    * **reuse**     – image tokens' temporal ID shifted to start at 0
                      (simulates KV-cache reuse from a context where the image
                      was at position 0).

    Parameters
    ----------
    model        : ``Qwen2_5_VLForConditionalGeneration``
    inputs       : processor output dict already on *device*
    image_mask   : ``[seq_len]`` bool tensor; True where a token is an image token
    metric_fn    : callable ``(a: Tensor, b: Tensor) -> Tensor`` mapping
                   ``[*, hidden] x [*, hidden]`` to per-token scalars ``[*]``
    decode_steps : number of greedy autoregressive decode steps to run
    device       : computation device

    Notes
    -----
    During the decode phase, the two passes use independent greedy tokens
    (``fresh_next`` and ``reuse_next``).  Because the reuse pass produces
    different logits, the generated sequences will diverge over time.  This is
    intentional: it captures the compounding effect of the positional mismatch
    on downstream generation, mirroring the real VLCache reuse scenario.

    Returns
    -------
    dict with keys
        ``"error_norms"`` : ``np.ndarray`` of shape ``[num_layers, prefill_len + decode_steps]``
        ``"prefill_len"`` : int
        ``"decode_len"``  : int
        ``"image_start"`` : int  – first image-token index in sequence
        ``"image_end"``   : int  – one-past-last image-token index
        ``"num_layers"``  : int
    """
    model.eval()
    seq_len = inputs["input_ids"].shape[1]

    std_pos, reuse_pos = get_fresh_and_reuse_position_ids(
        model, inputs, image_mask
    )

    # ------------------------------------------------------------------ #
    # Prefill
    # ------------------------------------------------------------------ #
    fresh_out = model(
        **inputs,
        position_ids=std_pos,
        output_hidden_states=True,
        use_cache=True,
    )
    reuse_out = model(
        **inputs,
        position_ids=reuse_pos,
        output_hidden_states=True,
        use_cache=True,
    )

    # hidden_states is a tuple of (num_layers + 1) tensors: embedding + each layer
    num_layers = len(fresh_out.hidden_states) - 1

    prefill_errors = np.zeros((num_layers, seq_len), dtype=np.float32)
    for l in range(num_layers):
        h_f = fresh_out.hidden_states[l + 1][0]   # [seq_len, H]
        h_r = reuse_out.hidden_states[l + 1][0]
        prefill_errors[l] = metric_fn(h_f, h_r).cpu().numpy()

    # ------------------------------------------------------------------ #
    # Autoregressive decode
    # ------------------------------------------------------------------ #
    fresh_past = fresh_out.past_key_values
    reuse_past = reuse_out.past_key_values

    # Greedy next token from both passes
    fresh_next = fresh_out.logits[0, -1].argmax(-1, keepdim=True).unsqueeze(0)  # [1, 1]
    reuse_next = reuse_out.logits[0, -1].argmax(-1, keepdim=True).unsqueeze(0)

    decode_errors = np.zeros((num_layers, decode_steps), dtype=np.float32)

    for step in range(decode_steps):
        cur_pos = seq_len + step
        # Decode-step position IDs: shape [3, 1, 1] for Qwen2.5-VL mrope
        pos_dec = torch.full(
            (3, 1, 1), cur_pos, device=device, dtype=torch.long
        )

        fresh_step = model(
            input_ids=fresh_next,
            past_key_values=fresh_past,
            position_ids=pos_dec,
            output_hidden_states=True,
            use_cache=True,
        )
        reuse_step = model(
            input_ids=reuse_next,
            past_key_values=reuse_past,
            position_ids=pos_dec,
            output_hidden_states=True,
            use_cache=True,
        )

        for l in range(num_layers):
            h_f = fresh_step.hidden_states[l + 1][0, 0]  # [H]
            h_r = reuse_step.hidden_states[l + 1][0, 0]
            decode_errors[l, step] = metric_fn(
                h_f.unsqueeze(0), h_r.unsqueeze(0)
            ).item()

        fresh_past = fresh_step.past_key_values
        reuse_past = reuse_step.past_key_values
        fresh_next = fresh_step.logits[0, 0].argmax(-1, keepdim=True).unsqueeze(0)
        reuse_next = reuse_step.logits[0, 0].argmax(-1, keepdim=True).unsqueeze(0)

    # ------------------------------------------------------------------ #
    # Assemble result
    # ------------------------------------------------------------------ #
    error_matrix = np.concatenate([prefill_errors, decode_errors], axis=1)

    img_idx = image_mask.nonzero(as_tuple=True)[0]
    image_start = int(img_idx[0])  if len(img_idx) > 0 else 0
    image_end   = int(img_idx[-1]) + 1 if len(img_idx) > 0 else 0

    return {
        "error_norms": error_matrix,
        "prefill_len": seq_len,
        "decode_len":  decode_steps,
        "image_start": image_start,
        "image_end":   image_end,
        "num_layers":  num_layers,
    }



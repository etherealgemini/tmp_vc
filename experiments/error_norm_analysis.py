# Vertical-line region markers used in all plots
_REGION_MARKERS = [
    ("image_start",  "Image start",       "tab:green"),
    ("image_end",    "Image end",          "tab:red"),
    ("prefill_len",  "Prefill → decode",   "tab:orange"),
]


def _add_region_markers(ax, metadata: dict) -> None:
    """Draw vertical dashed lines for the three region boundaries."""
    for key, label, color in _REGION_MARKERS:
        x = metadata.get(key)
        if x is not None:
            ax.axvline(
                x, color=color, linestyle="--", linewidth=1.2, label=label, alpha=0.8
            )


def plot_per_layer(
    error_norms: np.ndarray,
    output_dir: Path,
    metadata: dict,
    metric_label: str = "L2 norm",
) -> None:
    """
    Save one PNG per layer: error norm vs token index.

    The plot is intentionally independent of the recomputation method:
    it only requires the ``error_norms`` matrix produced by
    :func:`collect_error_norms`.  Future recompute-ratio curves can be
    overlaid by calling this function with additional ``error_norms`` arrays.

    Parameters
    ----------
    error_norms  : ``[num_layers, total_tokens]``
    output_dir   : directory where per-layer PNGs are saved
    metadata     : dict from :func:`collect_error_norms`
    metric_label : y-axis label string
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    num_layers, total_tokens = error_norms.shape
    token_indices = np.arange(total_tokens)

    for layer_idx in range(num_layers):
        fig, ax = plt.subplots(figsize=(10, 4))
        ax.plot(
            token_indices,
            error_norms[layer_idx],
            color="steelblue",
            linewidth=1.2,
            label="Reuse vs recompute",
        )
        _add_region_markers(ax, metadata)

        ax.set_xlabel("Token index")
        ax.set_ylabel(f"Error norm ({metric_label})")
        ax.set_title(f"Layer {layer_idx:02d} — Error norm vs token index")
        ax.legend(fontsize=8, loc="upper right")
        ax.grid(True, alpha=0.3)
        fig.tight_layout()
        fig.savefig(output_dir / f"layer_{layer_idx:02d}.png", dpi=120)
        plt.close(fig)


def plot_matrix(
    error_norms: np.ndarray,
    output_dir: Path,
    metadata: dict,
    metric_label: str = "L2 norm",
) -> None:
    """
    Save a large heatmap PNG showing all layers × all tokens.

    Parameters
    ----------
    error_norms  : ``[num_layers, total_tokens]``
    output_dir   : directory where the matrix PNG is saved
    metadata     : dict from :func:`collect_error_norms`
    metric_label : colorbar label string
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    num_layers, total_tokens = error_norms.shape

    fig_w = max(14, total_tokens // 30)
    fig_h = max(5,  num_layers  // 5)
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))

    im = ax.imshow(
        error_norms,
        aspect="auto",
        origin="lower",
        cmap="hot",
        interpolation="nearest",
    )
    plt.colorbar(im, ax=ax, label=f"Error norm ({metric_label})")

    for key, label, color in _REGION_MARKERS:
        x = metadata.get(key)
        if x is not None:
            ax.axvline(
                x, color=color, linestyle="--", linewidth=1.5,
                label=label, alpha=0.9
            )

    ax.set_xlabel("Token index")
    ax.set_ylabel("Layer index")
    ax.set_title("Error norm matrix — all layers × all tokens\n"
                 "(reuse vs recompute)")
    ax.legend(fontsize=8, loc="upper right")
    fig.tight_layout()
    fig.savefig(output_dir / "error_matrix.png", dpi=120)
    plt.close(fig)



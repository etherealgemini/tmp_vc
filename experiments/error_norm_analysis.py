# ---------------------------------------------------------------------------
# Error metrics – pluggable
# ---------------------------------------------------------------------------

def _l2(a: torch.Tensor, b: torch.Tensor) -> torch.Tensor:
    """Per-token L2 norm of (a - b); a, b have shape [..., hidden_size]."""
    return torch.norm(a.float() - b.float(), p=2, dim=-1)


def _mse(a: torch.Tensor, b: torch.Tensor) -> torch.Tensor:
    """Per-token mean-squared error of (a - b)."""
    return torch.mean((a.float() - b.float()) ** 2, dim=-1)


METRICS: Dict[str, Callable] = {
    "l2":  _l2,
    "mse": _mse,
}


# ---------------------------------------------------------------------------
# Dataset loader
# ---------------------------------------------------------------------------

def load_mmmu_pro_sample(
    dataset_path: Optional[str] = None,
    split: str = "test",
    index: int = 0,
) -> Tuple[Image.Image, str, dict]:
    """
    Load one sample from the MMMU-Pro Vision subset.

    Parameters
    ----------
    dataset_path : local directory of the dataset, or None to stream from
                   the HuggingFace Hub (requires internet).
    split        : "test" or "validation".
    index        : zero-based sample index.

    Returns
    -------
    (image, question_text, raw_sample_dict)
    """
    if not _HAS_DATASETS:
        raise ImportError("Install the `datasets` package to load MMMU-Pro.")

    if dataset_path and os.path.isdir(dataset_path):
        ds = _hf_load_dataset(dataset_path, split=split)
    else:
        ds = _hf_load_dataset(
            "MMMU/MMMU_Pro", "vision", split=split, trust_remote_code=True
        )

    sample = ds[index]
    image = sample.get("image_1") or sample.get("image")
    if image is None:
        raise ValueError(
            f"Sample {index} has no recognized image field "
            "(expected 'image_1' or 'image')."
        )

    question = sample.get("question", "What is shown in this image?")
    options = sample.get("options", [])
    if options:
        opts_text = "\n".join(
            f"{chr(65 + i)}. {opt}" for i, opt in enumerate(options)
        )
        question_full = (
            f"{question}\n\nOptions:\n{opts_text}\n\n"
            "Answer with the option letter only."
        )
    else:
        question_full = question

    return image, question_full, dict(sample)


# ---------------------------------------------------------------------------
# Input preparation
# ---------------------------------------------------------------------------

def _process_vision_info(messages):
    """Thin wrapper that works with or without qwen_vl_utils."""
    if _HAS_QWEN_VL_UTILS:
        return _qwen_process_vision_info(messages)
    # Minimal fallback: extract PIL images already embedded in messages
    images = []
    for msg in messages:
        for item in msg.get("content", []):
            if item.get("type") == "image":
                raw = item["image"]
                images.append(
                    raw if isinstance(raw, Image.Image)
                    else Image.open(raw).convert("RGB")
                )
    return images, []


def prepare_multimodal_input(
    processor,
    image: Image.Image,
    question: str,
    device: torch.device,
    dtype: torch.dtype,
) -> Tuple[dict, torch.BoolTensor]:
    """
    Build tokenised multimodal inputs for Qwen2.5-VL.

    Returns
    -------
    inputs     : dict ready to pass to model.forward()
    image_mask : BoolTensor [seq_len] marking image-token positions
    """
    messages = [
        {
            "role": "user",
            "content": [
                {"type": "image", "image": image},
                {"type": "text",  "text":  question},
            ],
        }
    ]
    text = processor.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    image_inputs, _ = _process_vision_info(messages)
    inputs = processor(
        text=[text],
        images=image_inputs,
        return_tensors="pt",
    )
    inputs = {
        k: v.to(device) if isinstance(v, torch.Tensor) else v
        for k, v in inputs.items()
    }
    if "pixel_values" in inputs:
        inputs["pixel_values"] = inputs["pixel_values"].to(dtype)

    # Locate image token positions in the sequence
    image_token_id = getattr(processor, "image_token_id", None)
    if image_token_id is None:
        image_token_id = getattr(
            getattr(processor, "tokenizer", processor), "image_token_id", 151655
        )
    image_mask = inputs["input_ids"][0] == image_token_id
    return inputs, image_mask


# ---------------------------------------------------------------------------
# Position-ID helpers
# ---------------------------------------------------------------------------

def get_fresh_and_reuse_position_ids(
    model,
    inputs: dict,
    image_mask: torch.BoolTensor,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """
    Return ``(standard_position_ids, reuse_position_ids)``.

    ``reuse_position_ids`` is identical to ``standard_position_ids`` except
    that, for image-token positions, the temporal (t) dimension is shifted
    backwards so that the first image token starts at t = 0.  This simulates
    the scenario where the image K/V cache was built in a reference request
    where the image appeared at position 0, and is now being reused in a new
    request where the image appears at position P > 0.

    The spatial (h, w) position IDs of image patches are left unchanged so
    that the 2-D structure of the image is preserved.
    """
    device = inputs["input_ids"].device

    # Try the model's own rope-index builder (specific to Qwen2.5-VL)
    try:
        std_pos, _ = model.get_rope_index(
            input_ids=inputs["input_ids"],
            image_grid_thw=inputs.get("image_grid_thw"),
            video_grid_thw=None,
            attention_mask=inputs.get("attention_mask"),
        )
    except (AttributeError, TypeError):
        # Fallback: plain 1-D position IDs replicated across all 3 mrope dims
        seq_len = inputs["input_ids"].shape[1]
        pos_1d = torch.arange(seq_len, device=device, dtype=torch.long).unsqueeze(0)
        std_pos = pos_1d.unsqueeze(0).expand(3, -1, -1).clone()

    reuse_pos = std_pos.clone()
    image_indices = image_mask.nonzero(as_tuple=True)[0]
    if len(image_indices) > 0:
        first_img_t = int(reuse_pos[0, 0, image_indices[0]])
        # Shift temporal dim back so the first image token is at t = 0
        reuse_pos[0, 0, image_mask] = reuse_pos[0, 0, image_mask] - first_img_t

    return std_pos, reuse_pos



#!/usr/bin/env python3
"""
Error-norm vs token-index analysis (Figure 2 style) for Qwen2.5-VL-3B-Instruct.

Experiment overview
-------------------
Two forward passes are run on the same multimodal input:

  * "recompute" (ground-truth): image tokens keep their natural 3-D rotary
    position IDs as generated by the Qwen2.5-VL processor.

  * "reuse"    (approximation): image tokens have their temporal (t) position
    IDs reset to [0, N_img), simulating KV-cache reuse where the image was
    originally processed at position 0 and is now encountered at position P
    (because a system-prompt prefix of P tokens precedes the image in the
    current request).  The h/w spatial IDs of image patches are preserved.

The per-token, per-layer error norm is metric_fn(h_reuse - h_recompute),
where h is the hidden state at the OUTPUT of each transformer block.

Region metadata (image span, prefill span, decode span) is embedded in the
plots via vertical dashed lines, matching the Figure 2 layout from the paper.

Usage
-----
    python experiments/error_norm_analysis.py \\
        --model_path ~/huggingface/Qwen2.5-VL-3B-Instruct \\
        --output_dir  outputs/error_norm \\
        --metric      l2 \\
        --decode_steps 20

See docs/error_norm_experiment.md for full documentation.
"""

